  if(idx===1) await page.screenshot({path:out+'/external-broker-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'إرسال',exact:true}).click();
  await page.getByRole('heading',{name:'تم استلام بياناتك'}).waitFor();
