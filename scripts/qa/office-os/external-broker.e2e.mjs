  await page.locator('[name="submitterRole"]').selectOption('EXTERNAL_BROKER');
  await page.locator('[name="externalBrokerOffice"]').fill('مكتب تعاون مستقل');
  await page.locator('[name="externalBrokerLicense"]').fill('1200012345');
