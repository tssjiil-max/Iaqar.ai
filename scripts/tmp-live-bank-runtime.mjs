import { chromium } from 'playwright';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const STAGING = 'https://iaqar-ai-staging--staging-9c4b0k7h.web.app';
const OUT = process.env.LIVE_DIAG_OUT || '/tmp/live-bank-runtime';
mkdirSync(OUT, { recursive: true });
const source = readFileSync('scripts/staging-bank-card-click-verify.mjs', 'utf8');
const phone = source.match(/const PHONE = process\.env\.STAGING_PHONE \|\| "([^"]+)";/)?.[1] || '';
const password = source.match(/const PASSWORD = process\.env\.STAGING_PASSWORD \|\| "([^"]+)";/)?.[1] || '';
if (!phone || !password) throw new Error('QA_LOGIN_NOT_FOUND');
const browser = await chromium.launch({headless:true});
const context = await browser.newContext({viewport:{width:390,height:844},locale:'ar-SA',timezoneId:'Asia/Riyadh'});
const page = await context.newPage();
await page.goto(STAGING,{waitUntil:'domcontentloaded',timeout:60000});
await page.waitForTimeout(2000);
const loginBtn = page.locator('button[data-go="login"]');
if (await loginBtn.count()) await loginBtn.click();
await page.locator('#loginForm input[name="phone"]').fill(phone);
await page.locator('#loginForm input[name="password"]').fill(password);
await page.locator('#loginForm button[type="submit"]').click();
await page.waitForTimeout(5000);
const main = page.locator("#mainTabOpportunities, button:has-text('العروض والطلبات')").first();
if (await main.count()) await main.click();
await page.waitForTimeout(700);
const sub = page.locator("#oppTabBank, button:has-text('القائمة')").first();
if (await sub.count()) await sub.click();
await page.waitForTimeout(2500);
const report = await page.evaluate(() => {
  const officeId=String(window.IAQAR?.office?.officeId||'');
  const ops=Array.isArray(window.IAQAR?.operationsItems)?window.IAQAR.operationsItems:[];
  const matchOps=ops.filter(o=>String(o.operationType||o.type||'').toUpperCase()==='MATCH_REVIEW').map(o=>({operationId:String(o.id||o.recordId||''),matchId:String(o.matchId||''),status:String(o.status||''),livingStage:String(o.livingStage||''),opportunityId:String(o.opportunityId||o.originOpportunityId||''),clientRequestId:String(o.clientRequestId||o.requestId||''),ownerOfferId:String(o.ownerOfferId||o.offerId||'')}));
  const cards=[...document.querySelectorAll('[data-cv2-inbox-item][data-opportunity-id]')].map(el=>String(el.getAttribute('data-opportunity-id')||''));
  const filters=[...document.querySelectorAll('[data-bank-action-filter]')].map(el=>({filter:String(el.getAttribute('data-bank-action-filter')||''),pressed:String(el.getAttribute('aria-pressed')||'')}));
  return {officeId,operationsCount:ops.length,matchOps,cards,filters};
});
writeFileSync(`${OUT}/report.json`,JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
await browser.close();
